package com.ryoma.frontend;

public class Player {
    // Attributes / Fields
    public String name;
    public int hp;
    public int power;
    public int spellCards;

    // Constructor
    public Player(String name, int hp, int power, int spellCards) {
        this.name = name;
        this.hp = hp;
        this.power = power;
        this.spellCards = spellCards;
    }
}
